DEFINE VIEW DEV_DBT_DEMO_BACKUP.MODELED.STG_LOYALTY__CUSTOMER_LOYALTY
AS
WITH SOURCE AS (
    SELECT * FROM DEV_DBT_DEMO_BACKUP.RAW.CUSTOMER_LOYALTY
),
