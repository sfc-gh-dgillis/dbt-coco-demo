        MARITAL_STATUS,
        CHILDREN_COUNT,
        SIGN_UP_DATE,
        BIRTHDAY_DATE,
        E_MAIL,
        PHONE_NUMBER,
        LAST_UPDATE_TS
    FROM SOURCE
)
SELECT * FROM RENAMED;

